// Prints docs/MIDI.md (markdown) from the parameter table (daisy/src/params.h): `make midi-doc`.
#include <cmath>
#include <cstdio>
#include <string>

#include "dsp/engine.h"
#include "param_store.h"
#include "params.h"

namespace {

using namespace btparam;

const char* TaperName(Taper t) {
    return t == Taper::kLog ? "log" : t == Taper::kEnum ? "enum" : t == Taper::kAudio ? "audio" : "linear";
}

const char* ControlName(Control c) {
    static const char* const kNames[] = {"", "SW1", "SW2", "SW3", "FS1", "FS2"};
    return kNames[int(c)];
}

const char* GroupName(Group g) {
    static const char* const kNames[] = {"global", "delay", "hall", "plate", "canyon", "eq", "knobs"};
    return kNames[int(g)];
}

std::string Num(float v) {
    char b[32];
    std::snprintf(b, sizeof b, "%g", double(v));
    return b;
}

}  // namespace

int main() {
    std::printf("<!-- Generated by `make midi-doc` (host/gen_midi_doc.cpp) from daisy/src/params.h. Do not edit. -->\n");
    std::printf("# Bad Tape: MIDI implementation\n\n");
    std::printf("Every parameter of the pedal can be set over the Seed's USB MIDI port: Control Change for the "
                "parameters with a CC (the factory knob functions, the switches, FS1 and FS2), 14-bit NRPN and SysEx "
                "for all %d of them. The parameter table `daisy/src/params.h` is the single source of truth; this file "
                "is generated from it.\n\n",
                int(kParamCount));

    std::printf("## Channels\n\n");
    std::printf("The pedal receives on all channels (omni) and never sends CC or NRPN: a MIDI change is applied "
                "silently (the log line `midi NAME = VALUE UNIT` reports the stored value). Changes made on the "
                "pedal's controls are not sent as MIDI either; with WATCH on, the SysEx link streams every change, "
                "MIDI included, as VALUE.\n\n");

    std::printf("## Control Change\n\n");
    std::printf("A CC value 0-127 maps to 0..1 along the parameter's taper (`value/127`, see Tapers). For an on/off "
                "parameter 0-63 is off and 64-127 is on.\n\n");
    std::printf("|CC|Parameter|Control|\n|---|---|---|\n");
    for (int cc = 0; cc < 128; ++cc) {
        const int id = FindByCc(uint8_t(cc));
        if (id >= 0) std::printf("|%d|`%s`|%s|\n", cc, kParams[id].name, ControlName(kParams[id].control));
    }
    std::printf("\n");

    std::printf("## NRPN\n\n");
    std::printf("- Select a parameter with CC 99 (NRPN MSB) = id >> 7 and CC 98 (NRPN LSB) = id & 0x7F; numbers >= %d "
                "are ignored.\n",
                int(kParamCount));
    std::printf("- CC 6 (data entry MSB) sets the parameter to code `msb << 7` at once; a following CC 38 (data entry "
                "LSB) refines it to `msb << 7 | lsb`. A CC 38 alone uses the last data MSB since the selection (0 if "
                "none).\n");
    std::printf("- The code (0-16383) maps to 0..1 as `code/16383` along the parameter's taper. Code 0 is exactly the "
                "minimum, 16383 exactly the maximum.\n");
    std::printf("- Data entry is ignored until both CC 99 and CC 98 have been received on that channel. CC 101/100 "
                "(RPN select) and the null NRPN (99 = 127, 98 = 127) deselect; CC 96/97 (increment/decrement) are "
                "ignored. Each channel keeps its own selection.\n\n");

    std::printf("## Tapers\n\n");
    std::printf("With `n` in 0..1 (CC `value/127`, NRPN/SysEx `code/16383`):\n\n");
    std::printf("- linear: `value = min + n * (max - min)`\n");
    std::printf("- log: `value = min * (max/min)^n`\n");
    std::printf("- audio: `value = min + (max - min) * (32^n - 1)/31`, like an A-taper pot: 15 %% of the range at "
                "n = 0.5\n");
    std::printf("- enum: `value = min + round(n * (max - min))`; the canonical code of an enum value is "
                "`round((value - min)/(max - min) * 16383)`\n\n");

    std::printf("## SysEx\n\n");
    std::printf("Frames are `F0 7D 62 02 <cmd> <payload> F7` (manufacturer 7D, device 62, version 02; "
                "`daisy/src/link.h`). Ids, counts and codes travel as two 7-bit bytes `hi = v >> 7`, `lo = v & 0x7F`. "
                "Version-01 frames (the previous one-byte-id format) are ignored, except that "
                "`daisy/tools/usb_log.py --dfu` sends DFU in both versions. "
                "`daisy/tools/usb_log.py` implements the host side (`--dump`, `--get`, `--set`, `--check-params`).\n\n");
    std::printf("|Direction|Command|Payload|Effect|\n|---|---|---|---|\n");
    std::printf("|host to pedal|`02` GET|`<id hi> <id lo>`|answered by VALUE|\n");
    std::printf("|host to pedal|`03` SET|`<id hi> <id lo> <hi> <lo>`|sets the parameter (as a MIDI write, see "
                "Arbitration); answered by VALUE with the stored code (an enum's canonical code)|\n");
    std::printf("|host to pedal|`04` DUMP|none|answered by one PARAM per id, then DUMP END; a DUMP during a dump "
                "restarts it|\n");
    std::printf("|host to pedal|`05` WATCH|`<on>` (0 or 1)|on: the pedal streams VALUE for every parameter whose code "
                "changed for any reason (knob, switch, FS1, FS2, link, MIDI), checked every 20 ms; knob jitter of a "
                "few codes is absorbed. Off is the boot default|\n");
    std::printf("|host to pedal|`07` SAVE|`<id hi> <id lo> ...`|saves each parameter's current value as its power-up "
                "value, in one flash write; answered by SAVED per id (only on success), then STORE|\n");
    std::printf("|host to pedal|`08` CLEAR|`<id hi> <id lo> ...`|forgets the saved values (power-up uses the default); "
                "same replies as SAVE; with nothing to change there is no flash write and the status is 0|\n");
    std::printf("|host to pedal|`09` SAVED?|none|answered by SAVED for every saveable id in id order, then SAVED "
                "END|\n");
    std::printf("|pedal to host|`13` VALUE|`<id hi> <id lo> <hi> <lo>`|the parameter's current code|\n");
    std::printf("|pedal to host|`14` PARAM|`<id hi> <id lo> <taper> <control> <cc> <group> <def hi> <def lo> <cur hi> "
                "<cur lo> <text>`|one table entry; text is ASCII `name\\|unit\\|min\\|max` (min/max as `%%g`)|\n");
    std::printf("|pedal to host|`15` DUMP END|`<count hi> <count lo>`|the dump is complete; count = %d|\n",
                int(kParamCount));
    std::printf("|pedal to host|`16` SAVED|`<id hi> <id lo> <has> <hi> <lo>`|has 1: the code of the saved value; has "
                "0: the code of the default|\n");
    std::printf("|pedal to host|`17` STORE|`<status>`|0 ok, 1 the flash write failed (nothing changed), 2 bad "
                "request (no write)|\n");
    std::printf("|pedal to host|`18` SAVED END|`<count hi> <count lo>`|the SAVED? answer is complete; count = %d "
                "saveable parameters|\n\n",
                kSaveableCount);
    std::printf("Saved values: SAVE persists a parameter's current value to flash (QSPI 0x903FE000, two 4 KB slots) "
                "as its power-up value; parameters on a switch or footswitch are not saveable. A SAVE/CLEAR with no "
                "id, an odd payload, an id >= %d or a parameter on a switch or footswitch logs "
                "`link: bad save message CC` and answers STORE 2. A WATCH with a wrong length or on > 1 logs "
                "`link: bad watch message`.\n\n",
                int(kParamCount));
    std::printf("A GET/SET with an id >= %d or a wrong length, or a DUMP with a payload, logs "
                "`link: bad param message CC` and gets no reply. Enum bytes in PARAM: taper 0 linear, 1 log, 2 enum, "
                "3 audio; "
                "control 0 none, 1-3 SW1-SW3, 4 FS1, 5 FS2; group 0 global, 1 delay, 2 hall, 3 plate, 4 canyon, 5 eq, "
                "6 knobs.\n\n",
                int(kParamCount));

    const int pickup = int(std::lround(kPickup * 100.0f));
    const auto blocksToMs = [](int blocks) {
        return blocks * int(btdsp::kBlockSize) * 1000 / int(btdsp::kSampleRate);
    };
    std::printf("## Arbitration\n\n");
    std::printf("What you see is what you get, with exceptions for MIDI, FS2 and remapping:\n\n");
    std::printf("- Knob slots: `knob_N_primary` and `knob_N_secondary` (parameter ids, %d = none) choose what knob "
                "N drives without FS2 and with FS2 held. Factory primaries:",
                int(kNoParam));
    for (int s = 0; s < kKnobs; ++s)
        std::printf("%s knob %d `%s`", s ? "," : "", s + 1, kParams[int(kParams[SlotAssignId(s)].def)].name);
    std::printf("; factory secondaries:");
    bool anySecondary = false;
    for (int s = kKnobs; s < kSlots; ++s) {
        const int id = int(kParams[SlotAssignId(s)].def);
        if (id == kNoParam) continue;
        std::printf("%s knob %d `%s`", anySecondary ? "," : "", s - kKnobs + 1, kParams[id].name);
        anySecondary = true;
    }
    std::printf("%s. Switch and footswitch parameters and the assignments themselves cannot be assigned (they mean "
                "none). Any `*_space` id means the active algorithm's Space macro.\n",
                anySecondary ? " (the others none)" : " none");
    std::printf("- Primaries are what you see is what you get. A MIDI or SysEx write to a parameter on a slot holds "
                "it until that slot's knob moves more than %d %% of its travel from where it was at the write; then "
                "the knob takes the parameter back (the log shows `knob N takes NAME`, or `knob N fs2 takes NAME` for "
                "a secondary).\n",
                pickup);
    std::printf("- FS2: pressed after %d ms of steady contact, released after %d ms. While it is held a knob drives "
                "only its secondary, once the knob has moved more than %d %% from where it was at the press. A knob "
                "moved more than %d %% while FS2 was held keeps its primary until it moves more than %d %% from where "
                "it was at the release.\n",
                blocksToMs(btctl::kShiftPressBlocks), blocksToMs(btctl::kShiftReleaseBlocks), pickup, pickup,
                pickup);
    std::printf("- A parameter on more than one slot follows the knob that moved last.\n");
    std::printf("- A newly assigned parameter keeps its value until its knob moves more than %d %%.\n", pickup);
    std::printf("- A switch that changes position always sets its parameter; a switch that has not moved leaves a "
                "MIDI value alone. FS1 toggles bypass. Releasing FS2 toggles `delay_sos` when `delay_sos_mode` is not "
                "off, no knob moved more than %d %% while FS2 was held and no toggle changed position.\n",
                pickup);
    std::printf("- A Space slot drives the active reverb algorithm's macro (SW3 / `reverb_algo`): `%s` (plate), `%s` "
                "(hall) or `%s` (canyon). The others keep their last value. A held Space parameter stays held when "
                "its algorithm becomes active, until its knob moves more than %d %%.\n",
                kParams[SpaceParam(btctl::Algo::kPlate)].name, kParams[SpaceParam(btctl::Algo::kHall)].name,
                kParams[SpaceParam(btctl::Algo::kCanyon)].name, pickup);
    std::printf("- Parameters on no slot keep whatever MIDI last set (default or saved value at power-on).\n");
    std::printf("- Saved values apply at power-up; the knob replaces the saved value of a parameter on a primary "
                "slot. A saved link target is held like a MIDI write, anchored at its source's first change after "
                "power-up, until the source moves more than %d %% from there.\n",
                pickup);
    std::printf("- Links: when a source parameter changes (from its knob or MIDI) it writes its targets, except "
                "targets on a knob slot (the knob owns them). A MIDI write to a target holds it until the source "
                "moves more than %d %% of its travel from where it was at the write. Each Space macro runs 0-100 %% "
                "(n = value/100) from a small, short space to a large, long one, and its default gives its targets' "
                "defaults:",
                pickup);
    for (size_t i = 0; i < std::size(kLinks); ++i)
        std::printf("%s `%s` writes `%s` = %s", i ? ";" : "", kParams[kLinks[i].source].name,
                    kParams[kLinks[i].target].name, kLinks[i].law);
    std::printf(".\n\n");

    std::printf("## Parameters\n\n");
    std::printf("Ids are fixed (new parameters are appended). Smoothing is the one-pole time constant the DSP applies "
                "to changes; 0 means the stage handles changes itself (crossfade, glide or switch).\n\n");
    std::printf("|Id|Name|Unit|Min|Max|Default|Taper|Control|CC|Smoothing ms|Group|\n");
    std::printf("|---|---|---|---|---|---|---|---|---|---|---|\n");
    for (const ParamDef& d : kParams) {
        std::printf("|%d|`%s`|%s|%s|%s|%s|%s|%s|%s|%s|%s|\n", d.id, d.name, d.unit, Num(d.min).c_str(),
                    Num(d.max).c_str(), Num(d.def).c_str(), TaperName(d.taper), ControlName(d.control),
                    d.cc ? std::to_string(d.cc).c_str() : "", Num(d.smoothMs).c_str(), GroupName(d.group));
    }
    return 0;
}
